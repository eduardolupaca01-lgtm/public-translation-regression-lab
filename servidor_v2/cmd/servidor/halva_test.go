func TestHalvaNativeInstallRoundTripAndRecover(t *testing.T){
 for _,kind:=range []string{"MV","MZ"}{t.Run(kind,func(t *testing.T){
  root,original,registry:=halvaFixture(t,kind)
  game:=filepath.Join(root,"Dragonhouse.GameBootstrapper.exe")
  pkg,e:=readPackage(fakePackage(t));if e!=nil{t.Fatal(e)};defer pkg.Close()
  if got,e:=detectInstallTarget(game);e!=nil||got!=kind+" Halva"{t.Fatalf("detect %s: %v",got,e)}
  untouched:=map[string]string{}
  for _,n:=range []string{"GameConfig.sbcf","GamePackages/DatabasePackage.halva","GamePackages/AssetsPackage.halva","GamePackages/AudioPackage.halva","Game.exe","Dragonhouse.GameBootstrapper.exe","userdata/save.rmmzsave"}{
   b,e:=os.ReadFile(filepath.Join(root,filepath.FromSlash(n)));if e!=nil{t.Fatal(e)};untouched[n]=hash(b)
  }
  if e=Install(game,pkg);e!=nil{t.Fatal(e)}
  id,e:=installedPackageIdentity(game,pkg);if e!=nil||!strings.Contains(id,kind+"-HALVA"){t.Fatalf("identity %s %v",id,e)}
  packed,e:=halvaOpen(halvaEngineFile(root));if e!=nil{t.Fatal(e)}
  updated,e:=halvaRead(packed,"js/plugins.js",4*1024*1024);if e!=nil{t.Fatal(e)}
  _,old,e:=parseRegistry(registry);if e!=nil{t.Fatal(e)}
  _,newList,e:=parseRegistry(updated);if e!=nil||len(newList)!=len(old)+1{t.Fatalf("registry %v",e)}
  for i:=range old{
   a,_:=json.Marshal(old[i]);b,_:=json.Marshal(newList[i]);if !bytes.Equal(a,b){t.Fatal("original plugin changed")}
  }
  var params map[string]string
  canonical,e:=filepath.EvalSymlinks(root);if e!=nil{t.Fatal(e)}
  if json.Unmarshal(newList[len(old)]["parameters"],&params)!=nil||params["iaHalvaRoot"]!=canonical{t.Fatal("canonical persistent root absent")}
  aInfo,e:=os.Stat(root);if e!=nil{t.Fatal(e)}
  bInfo,e:=os.Stat(params["iaHalvaRoot"]);if e!=nil||!os.SameFile(aInfo,bInfo){t.Fatal("persistent root is a different directory")}
  before,e:=halvaDecode(original);if e!=nil{t.Fatal(e)}
  for key,f:=range before.entries{
   if key=="js/plugins.js"{continue}
   next:=packed.entries[key];if next==nil||f.Name!=next.Name||f.CRC32!=next.CRC32{t.Fatalf("entry changed %s",key)}
  }
  cache:=filepath.Join(root,brandFolder,".local","Rpg","cache","keep.txt")
  cookFixtureFile(t,filepath.Dir(cache),filepath.Base(cache),[]byte("persistent"))
  if e=Install(game,pkg);e!=nil{t.Fatal("same version retry",e)}
  if e=RecoverGame(game);e!=nil{t.Fatal(e)}
  restored,e:=os.ReadFile(halvaEngineFile(root));if e!=nil||!bytes.Equal(restored,original){t.Fatal("original not restored")}
  if e=RecoverGame(game);e!=nil{t.Fatal("recover not idempotent",e)}
  if e=Install(game,pkg);e!=nil{t.Fatal("reinstall",e)}
  for n,want:=range untouched{
   b,e:=os.ReadFile(filepath.Join(root,filepath.FromSlash(n)));if e!=nil||hash(b)!=want{t.Fatalf("original changed %s",n)}
  }
  b,e:=os.ReadFile(cache);if e!=nil||string(b)!="persistent"{t.Fatal("cache lost")}
  changed:=[]byte("external change; not owned")
  if e=os.WriteFile(halvaEngineFile(root),changed,0600);e!=nil{t.Fatal(e)}
  if e=RecoverGame(game);e==nil{t.Fatal("unexpected overwrite")}
  b,_=os.ReadFile(halvaEngineFile(root));if !bytes.Equal(b,changed){t.Fatal("changed package overwritten")}
 })}
}

func TestHalvaRejectsInvalidAndUnsafeArchives(t *testing.T){
 for _,files:=range []map[string][]byte{
  {"..\\escape.js":[]byte("no")},
  {"js\\plugins.js":[]byte("a"),"JS/plugins.js":[]byte("b")},
  {"C:\\outside.js":[]byte("no")},
 }{
  if _,e:=halvaDecode(syntheticHalva(t,files));e==nil{t.Fatal("unsafe entry accepted")}
 }
 if _,e:=halvaDecode([]byte("not plaintext Brotli/ZIP"));e==nil{t.Fatal("unsupported package accepted")}
 root,_,_:=halvaFixture(t,"MZ")
 p,e:=readPackage(fakePackage(t));if e!=nil{t.Fatal(e)};defer p.Close()
 if e=os.WriteFile(filepath.Join(halvaPackDir(root),"DatabasePackage.halva"),[]byte("unsupported"),0600);e!=nil{t.Fatal(e)}
 if e=Install(filepath.Join(root,"Game.exe"),p);e==nil{t.Fatal("unsupported DB accepted")}
 if _,e=os.Lstat(filepath.Join(root,brandFolder));!os.IsNotExist(e){t.Fatal("wrote to unsupported game")}
}

