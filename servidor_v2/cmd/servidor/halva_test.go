func syntheticHalva(t *testing.T,files map[string][]byte)[]byte{
 t.Helper()
 var raw bytes.Buffer
 zw:=zip.NewWriter(&raw)
 for name,value:=range files{
  w,e:=zw.CreateHeader(&zip.FileHeader{Name:name,Method:zip.Store});if e!=nil{t.Fatal(e)}
  if _,e=w.Write(value);e!=nil{t.Fatal(e)}
 }
 if e:=zw.Close();e!=nil{t.Fatal(e)}
 var encoded bytes.Buffer
 w:=brotli.NewWriterLevel(&encoded,1)
 if _,e:=w.Write(raw.Bytes());e!=nil{t.Fatal(e)}
 if e:=w.Close();e!=nil{t.Fatal(e)}
 return encoded.Bytes()
}

