# encoding: UTF-8
# Synthetic XP window contract. Win32API here is a test double for the
# 32-bit RGSS API; the installed Windows helper and OPUS worker are real.
require 'rbconfig'
class Win32API
  def initialize(lib,func,args,result)
    @func=func
  end
  def from_wide(value)
    value.dup.force_encoding('UTF-16LE').encode('UTF-8').sub(/\0.*\z/m,'')
  end
  def write_wide(text,out)
    data=text.encode('UTF-16LE').b
    out[0,data.bytesize+2]=data+"\0\0".b
    data.bytesize/2
  end
  def call(*args)
    case @func
    when 'GetModuleFileNameW'
      write_wide(File.expand_path('Game.exe').tr('/','\\'),args[1])
    when 'GetFullPathNameW'
      write_wide(File.expand_path(from_wide(args[0])).tr('/','\\'),args[2])
    when 'ShellExecuteW'
      helper=from_wide(args[2])
      expected=File.expand_path('IA Traductora/.local/Rpg/engine/rpgxp-launcher.exe').tr('/','\\')
      raise 'unexpected launcher' unless helper==expected
      flags=from_wide(args[3]).split(' ')
      raise 'unexpected arguments' unless flags==['--xp-launch-parent',Process.pid.to_s]
      $xp_launcher=Process.spawn([helper,helper],*flags,:chdir=>Dir.pwd,:out=>File::NULL,:err=>File::NULL)
      33
    else
      raise 'unexpected native API'
    end
  end
end
class Game_Temp
  attr_accessor :message_text,:choice_proc,:choice_start,:choice_max,:num_input_variable_id
  def initialize;@num_input_variable_id=0;end
end
class Window_Message
  attr_reader :painted,:paints
  def initialize;@contents_showing=false;@fade_in=@fade_out=false;@paints=0;end
  def update
    if !@contents_showing && $game_temp.message_text
      refresh
      @contents_showing=true
    end
  end
  def refresh
    @paints+=1
    @painted=$game_temp.message_text.dup
    $game_temp.message_text.replace('')
  end
end
